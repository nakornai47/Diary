const fs = require('fs');
const path = require('path');

const distDir = path.join(__dirname, '..', 'dist');
const indexPath = path.join(distDir, 'index.html');
const public404Path = path.join(__dirname, '..', 'public', '404.html');
const dist404Path = path.join(distDir, '404.html');

if (!fs.existsSync(distDir)) {
  console.error('dist/ directory not found. Run expo export first.');
  process.exit(1);
}

// Copy 404.html to dist so gh-pages uploads it
fs.copyFileSync(public404Path, dist404Path);

// Expo's web export places assets that originally come from node_modules under
// `dist/assets/node_modules/...`. Because the project's root `.gitignore`
// ignores `node_modules/`, `gh-pages` does not upload those files even though
// they live inside `dist/`. To work around this, copy every asset out from
// `dist/assets/node_modules/` to `dist/assets/` and rewrite JS bundle
// references so the URLs no longer contain `node_modules/`.
const assetsDir = path.join(distDir, 'assets');
const nodeModulesAssetsDir = path.join(assetsDir, 'node_modules');

if (fs.existsSync(nodeModulesAssetsDir)) {
  function copyRecursive(src, dest) {
    if (fs.statSync(src).isDirectory()) {
      if (!fs.existsSync(dest)) {
        fs.mkdirSync(dest, { recursive: true });
      }
      for (const entry of fs.readdirSync(src)) {
        copyRecursive(path.join(src, entry), path.join(dest, entry));
      }
    } else {
      fs.copyFileSync(src, dest);
    }
  }

  for (const entry of fs.readdirSync(nodeModulesAssetsDir)) {
    copyRecursive(
      path.join(nodeModulesAssetsDir, entry),
      path.join(assetsDir, entry),
    );
  }

  fs.rmSync(nodeModulesAssetsDir, { recursive: true, force: true });
  console.log('Relocated assets from dist/assets/node_modules/ to dist/assets/');

  // Rewrite references inside JS bundles
  const jsDir = path.join(distDir, '_expo', 'static', 'js', 'web');
  if (fs.existsSync(jsDir)) {
    const jsFiles = fs
      .readdirSync(jsDir)
      .filter((f) => f.endsWith('.js'))
      .map((f) => path.join(jsDir, f));

    for (const jsFile of jsFiles) {
      let content = fs.readFileSync(jsFile, 'utf8');
      const original = content;
      // Replace both absolute (with base URL) and relative references
      content = content.replace(
        /\/Diary\/assets\/node_modules\//g,
        '/Diary/assets/',
      );
      if (content !== original) {
        fs.writeFileSync(jsFile, content);
        console.log(`Rewrote asset paths in ${path.relative(distDir, jsFile)}`);
      }
    }
  }
}

// Inject script to restore the original path from the query string
// generated by public/404.html on GitHub Pages
const spaScript = `  <script type="text/javascript">
    (function(l) {
      if (l.search[1] === '/') {
        var decoded = l.search.slice(1).split('&').map(function(s) {
          return s.replace(/~and~/g, '&');
        }).join('?');
        window.history.replaceState(null, null,
          l.pathname.slice(0, -1) + decoded + l.hash
        );
      }
    }(window.location))
  </script>`;

let indexHtml = fs.readFileSync(indexPath, 'utf8');

if (!indexHtml.includes('l.search[1] === \'/\'')) {
  indexHtml = indexHtml.replace('<head>', '<head>\n' + spaScript);
  fs.writeFileSync(indexPath, indexHtml);
  console.log('Injected SPA redirect script into dist/index.html');
} else {
  console.log('SPA redirect script already present');
}

console.log('Copied 404.html to dist/');
